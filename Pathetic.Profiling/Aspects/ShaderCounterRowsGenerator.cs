using Microsoft.CodeAnalysis.CSharp;
using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Pathetic.Profiling.Aspects;

/// <summary>Generates <c>Rows()</c> of a ShaderCounterStats from the properties marked with [ShaderCounter].</summary>
[Generator(LanguageNames.CSharp)]
public sealed class ShaderCounterRowsGenerator : IIncrementalGenerator
{
    private const string RowType = "global::Pathetic.Profiling.Statistics.ShaderCounterRow";

    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<ImmutableArray<Row>> rows = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                $"{typeof(ShaderCounterAttribute).Namespace}.{nameof(ShaderCounterAttribute)}",
                static (node, _) => node is PropertyDeclarationSyntax,
                static (attributeContext, _) => ToRow(attributeContext))
            .Collect();

        context.RegisterSourceOutput(rows, static (output, found) =>
        {
            foreach (IGrouping<string, Row> type in found.GroupBy(row => row.Type).OrderBy(group => group.Key, StringComparer.Ordinal))
                output.AddSource($"{type.Key.Replace("global::", string.Empty)}.ShaderCounters.g.cs", SourceText.From(Write(type), System.Text.Encoding.UTF8));
        });
    }

    private static Row ToRow(GeneratorAttributeSyntaxContext context)
    {
        var property = (IPropertySymbol)context.TargetSymbol;
        AttributeData attribute = context.Attributes[0];

        T Named<T>(string name, T fallback) =>
            attribute.NamedArguments.FirstOrDefault(argument => argument.Key == name).Value.Value is T value ? value : fallback;

        return new Row(
            Type: property.ContainingType.ToDisplayString(TypeFormat),
            Name: $"{attribute.ConstructorArguments[0].Value}",
            Property: property.Name,
            Order: Named(nameof(ShaderCounterAttribute.Order), 0),
            Format: Named<string?>(nameof(ShaderCounterAttribute.Format), null),
            Suffix: Named(nameof(ShaderCounterAttribute.Suffix), string.Empty));
    }

    private static string Write(IEnumerable<Row> rows)
    {
        Row[] ordered = [.. rows.OrderBy(row => row.Order).ThenBy(row => row.Name, StringComparer.Ordinal)];
        string type = ordered[0].Type;
        int namespaceEnd = type.LastIndexOf('.');
        string typeName = type.Substring(namespaceEnd + 1);
        string? @namespace = namespaceEnd > 0 ? type.Substring("global::".Length, namespaceEnd - "global::".Length) : null;

        string lines = string.Join(",\n", ordered.Select(row =>
            $"            new {RowType}({Literal(row.Name)}, string.Format(global::System.Globalization.CultureInfo.CurrentCulture, {Literal($"{{0:{row.Format}}}{{1}}")}, {row.Property}, {Literal(row.Suffix)}))"));

        string body = $$"""
            partial class {{typeName}}
            {
                public override global::System.Collections.Generic.IReadOnlyList<{{RowType}}> Rows()
                {
                    if (!HasValues)
                        return [];

                    return
                    [
            {{lines}}
                    ];
                }
            }
            """;

        return $"// <auto-generated/>\n#pragma warning disable CS1591\n#nullable enable\n\n{(@namespace is null ? body : $"namespace {@namespace}\n{{\n{body}\n}}")}\n";
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private sealed record Row(string Type, string Name, string Property, int Order, string? Format, string Suffix);
}
