using Microsoft.CodeAnalysis.CSharp;
using System.Collections.Immutable;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Pathetic.Shaders.Generators;

/// <summary>Generates <c>ResourceName</c>: one constant per resource (buffer, texture) the shaders declare, named like in the shader.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class ResourceNameGenerator : IIncrementalGenerator
{
    // A global resource declaration such as "RWTexture2D<float4> color;" or "StructuredBuffer<Plane, ScalarDataLayout> planes;".
    private static readonly Regex Declaration = new(
        @"^[ \t]*(?:RW)?(?:StructuredBuffer|ByteAddressBuffer|Texture\w*|ConstantBuffer|SamplerState)\b(?:\s*<[^;>]*>)?\s+(?<name>[A-Za-z_]\w*)\s*;",
        RegexOptions.Compiled | RegexOptions.Multiline);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<ImmutableArray<string>> sources = ShaderSources.Read(context);

        context.RegisterSourceOutput(sources.Combine(ShaderSources.AssemblyName(context)), static (output, input) =>
        {
            (ImmutableArray<string> shaders, string assembly) = input;
            string[] names =
            [
                .. shaders
                    .SelectMany(shader => Declaration.Matches(shader).Cast<Match>().Select(match => match.Groups["name"].Value))
                    .Distinct(StringComparer.Ordinal)
                    .OrderBy(name => name, StringComparer.Ordinal),
            ];

            if (names.Length > 0)
                output.AddSource("ResourceName.g.cs", SourceText.From(Write(assembly, names), Encoding.UTF8));
        });
    }

    private static string Write(string assembly, string[] names)
    {
        string constants = string.Join("\n", names.Select(name =>
            $"        public const string {char.ToUpperInvariant(name[0])}{name.Substring(1)} = {SymbolDisplay.FormatLiteral(name, quote: true)};"));

        return $$"""
            // <auto-generated/>
            #pragma warning disable CS1591
            namespace {{assembly}}
            {
                public static class ResourceName
                {
            {{constants}}
                }
            }
            """;
    }
}
