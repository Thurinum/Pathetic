using System.Collections.Immutable;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Pathetic.Shaders.Generators;

/// <summary>
/// Finds every profiling counter the shaders use (<c>PROFILE_ADD(Name, ...)</c>, <c>PROFILE_MAX(Name, ...)</c>)
/// and generates the matching enum and the macros the shader compiler is given.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ShaderCounterGenerator : IIncrementalGenerator
{
    private const int MaxCounters = 32;
    private const string AddMacro = "PROFILE_ADD";
    private const string MaxMacro = "PROFILE_MAX";

    // Counter macros take the bare name: PROFILE_ADD(Paths, 1).
    private static readonly Regex MacroUse = new($@"\b(?<macro>{AddMacro}|{MaxMacro})\s*\(\s*(?<name>[A-Z]\w*)", RegexOptions.Compiled);

    // Helper code refers to counters by their index macro: ProfileAdd(PROFILE_Rays, 1).
    private static readonly Regex IndexUse = new(@"\bProfile(?<kind>Add|Max)\s*\(\s*PROFILE_(?<name>[A-Z]\w*)|\bPROFILE_(?<name>[A-Z][a-z]\w*)\b", RegexOptions.Compiled);

    private static readonly DiagnosticDescriptor TooManyCounters = new(
        id: "PATHSHADER001",
        title: "Too many shader counters",
        messageFormat: "The shaders use {0} profiling counters but at most {1} are supported",
        category: "Pathetic.Shaders",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<ImmutableArray<string>> sources = ShaderSources.Read(context);

        context.RegisterSourceOutput(sources.Combine(ShaderSources.AssemblyName(context)), static (output, input) =>
        {
            (ImmutableArray<string> shaders, string assembly) = input;
            Counter[] counters = Find(shaders);
            if (counters.Length == 0)
                return;

            if (counters.Length > MaxCounters)
            {
                output.ReportDiagnostic(Diagnostic.Create(TooManyCounters, Location.None, counters.Length, MaxCounters));
                return;
            }

            output.AddSource("ShaderCounters.g.cs", SourceText.From(Write(assembly, counters), Encoding.UTF8));
        });
    }

    private static Counter[] Find(ImmutableArray<string> shaders)
    {
        Dictionary<string, bool> isMax = [];

        foreach (string shader in shaders)
        {
            foreach (Match use in MacroUse.Matches(shader))
                Note(isMax, use.Groups["name"].Value, use.Groups["macro"].Value == MaxMacro);

            foreach (Match use in IndexUse.Matches(shader))
                Note(isMax, use.Groups["name"].Value, use.Groups["kind"].Value == "Max");
        }

        return [.. isMax.OrderBy(entry => entry.Key, StringComparer.Ordinal).Select((entry, index) => new Counter(entry.Key, index, entry.Value))];
    }

    private static void Note(Dictionary<string, bool> isMax, string name, bool max) =>
        isMax[name] = (isMax.TryGetValue(name, out bool known) && known) || max;

    private static string Write(string assembly, Counter[] counters)
    {
        uint maxMask = counters.Where(counter => counter.IsMax).Aggregate(0u, (mask, counter) => mask | (1u << counter.Index));

        string members = string.Join(",\n", counters.Select(counter => $"        {counter.Name} = {counter.Index}"));
        string macros = string.Join(",\n", counters.Select(counter => $"            (\"PROFILE_{counter.Name}\", \"{counter.Index}\")"));

        return $$"""
            // <auto-generated/>
            #pragma warning disable CS1591
            #nullable enable

            namespace {{assembly}}.Generated
            {
                /// <summary>Every profiling counter used by the shaders.</summary>
                public enum ShaderCounter
                {
            {{members}}
                }

                public sealed class ShaderCounterLayout : global::Pathetic.Profiling.Gpu.IShaderCounterLayout
                {
                    public int Count => {{counters.Length}};

                    public global::System.Collections.Generic.IEnumerable<(string Name, string Value)> Macros =>
                    [
                        ("PROFILE_COUNTERS", "1"),
                        ("PROFILE_COUNTER_COUNT", "{{counters.Length}}"),
                        ("PROFILE_MAX_COUNTER_MASK", "{{maxMask}}u"),
            {{macros}}
                    ];
                }
            }
            """;
    }

    private sealed record Counter(string Name, int Index, bool IsMax);
}
