using System.Text;

namespace Pathetic.Slang.Tool;

internal sealed class CodeWriter
{
    private readonly StringBuilder _builder = new();
    private int _indent;

    public void Line(string text = "")
    {
        if (text.Length > 0)
            _builder.Append(' ', _indent * 4).Append(text);

        _builder.Append('\n');
    }

    public void Open(string text)
    {
        Line(text);
        _indent++;
    }

    public void Close(string text)
    {
        _indent--;
        Line(text);
    }

    public override string ToString() => _builder.ToString();
}

internal static class Identifier
{
    private static readonly HashSet<string> Reserved =
    [
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
        "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
        "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
        "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override",
        "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
        "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    ];

    public static string Escape(string name) => Reserved.Contains(name) ? "@" + name : name;
}

internal static class SourceEmitter
{
    public static string EmitRefs(string targetNamespace)
    {
        CodeWriter writer = new();

        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line($"namespace {targetNamespace};");
        writer.Line();

        EmitRef(writer, "TextureRef", null);
        EmitRef(writer, "MutableTextureRef", "TextureRef");
        EmitRef(writer, "SamplerRef", null);
        EmitRef(writer, "UniformBufferRef", null);
        EmitRef(writer, "BufferRef", null);
        EmitRef(writer, "MutableBufferRef", "BufferRef");

        return writer.ToString();
    }

    public static string EmitModule(string targetNamespace, ModuleJson module)
    {
        CodeWriter writer = new();

        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();

        if (module.Types.Count > 0)
        {
            writer.Line("using System.Runtime.InteropServices;");
            writer.Line();
        }

        writer.Line($"namespace {targetNamespace}.{Identifier.Escape(module.Module)};");
        writer.Line();
        writer.Line("public static class Resources");
        writer.Open("{");
        writer.Line($"public const string ModuleName = \"{module.Module}\";");

        if (module.Bindings.Count > 0)
            writer.Line();

        foreach (BindingJson binding in module.Bindings)
        {
            ResolveToken(binding.Kind, out string token);
            writer.Line($"public static readonly {token} {Identifier.Escape(binding.Name)} = new(\"{binding.Name}\");");
        }

        writer.Close("}");

        foreach (TypeJson type in module.Types)
        {
            writer.Line();

            writer.Line($"[StructLayout(LayoutKind.Explicit, Size = {type.Size})]");
            writer.Line($"public record struct {Identifier.Escape(type.Name)}");
            writer.Open("{");
            writer.Line($"public const int SizeInBytes = {type.Size};");

            foreach (FieldJson field in type.Fields)
                writer.Line($"[FieldOffset({field.Offset})] public {field.CsType} {Identifier.Escape(field.Name)};");

            writer.Close("}");
        }

        return writer.ToString();
    }

    private static void EmitRef(CodeWriter writer, string name, string? convertsTo)
    {
        writer.Line($"public readonly record struct {name}(string Value)");
        writer.Open("{");
        writer.Line($"public static implicit operator string({name} value) => value.Value;");

        if (convertsTo is not null)
            writer.Line($"public static implicit operator {convertsTo}({name} value) => new(value.Value);");

        writer.Close("}");
        writer.Line();
    }

    private static void ResolveToken(string kind, out string token)
    {
        token = kind switch
        {
            "Texture" => "TextureRef",
            "MutableTexture" => "MutableTextureRef",
            "Sampler" => "SamplerRef",
            "UniformBuffer" => "UniformBufferRef",
            "BufferRead" => "BufferRef",
            "BufferReadWrite" => "MutableBufferRef",
            _ => throw new ToolException($"Unsupported binding kind '{kind}'."),
        };
    }
}
