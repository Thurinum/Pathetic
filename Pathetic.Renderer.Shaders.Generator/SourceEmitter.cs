using System.Text;

namespace Pathetic.Renderer.Shaders.Generator;

internal sealed class CodeWriter
{
    private readonly StringBuilder _builder = new();
    private int _indent;

    public void Line(string text = "")
    {
        if (text.Length > 0)
            _builder.Append(' ', _indent * 4).Append(text);

        _builder.Append("\r\n");
    }

    public void Open(string text)
    {
        Line(text);
        _indent++;
    }

    public void Close(string text)
    {
        _indent--;
        Line(text);
    }

    public override string ToString() => _builder.ToString();
}

internal static class Identifier
{
    private static readonly HashSet<string> Reserved =
    [
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
        "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
        "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
        "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override",
        "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
        "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    ];

    public static string Escape(string name) => Reserved.Contains(name) ? "@" + name : name;
}

internal static class SourceEmitter
{
    public static string EmitModule(string targetNamespace, ModuleModel module)
    {
        CodeWriter writer = new();

        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();

        if (module.Types.Count > 0)
        {
            writer.Line("using System.Runtime.InteropServices;");
            writer.Line();
        }

        List<BindingModel> bindings = module.Bindings;

        if (module.Pipeline is not null)
            bindings = [.. bindings.Where(binding => module.Pipeline.Parameters.Any(parameter => parameter.Name == binding.Name))];

        if (module.Pipeline is not null || bindings.Count > 0)
        {
            writer.Line($"namespace {targetNamespace}.Resources");
            writer.Open("{");
            writer.Line($"public static class {Identifier.Escape(module.Module)}");
            writer.Open("{");
            writer.Line($"public const string ModuleName = \"{module.Module}\";");

            if (bindings.Count > 0)
                writer.Line();

            foreach (BindingModel binding in bindings)
                writer.Line($"public static readonly {binding.Kind}Ref {Identifier.Escape(binding.Name)} = new(\"{binding.Name}\");");

            writer.Close("}");
            writer.Close("}");
            writer.Line();
        }

        if (module.Types.Count > 0)
        {
            writer.Line($"namespace {targetNamespace}");
            writer.Open("{");

            foreach (TypeModel type in module.Types)
            {
                writer.Line();
                writer.Line($"[StructLayout(LayoutKind.Explicit, Size = {type.Size})]");
                writer.Line($"public record struct {Identifier.Escape(type.Name)}");
                writer.Open("{");
                writer.Line($"public const int SizeInBytes = {type.Size};");

                foreach (FieldModel field in type.Fields)
                    writer.Line($"[FieldOffset({field.Offset})] public {field.CsType} {Identifier.Escape(field.Name)};");

                writer.Close("}");
            }

            writer.Close("}");
        }

        return writer.ToString();
    }

    public static string EmitShaderModules(IEnumerable<ModuleModel> modules)
    {
        CodeWriter writer = new();

        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line("namespace Pathetic.Renderer.Shaders");
        writer.Open("{");
        writer.Line("public enum ShaderResourceKind");
        writer.Open("{");

        foreach (BindingKind kind in Enum.GetValues<BindingKind>())
            writer.Line($"{kind},");

        writer.Close("}");
        writer.Line();
        writer.Line("public static class ShaderModules");
        writer.Open("{");
        writer.Line("public static readonly IReadOnlyDictionary<string, ShaderModule> All = new Dictionary<string, ShaderModule>(StringComparer.Ordinal)");
        writer.Open("{");

        foreach (ModuleModel module in modules.Where(static module => module.Pipeline is not null).OrderBy(static module => module.Module, StringComparer.Ordinal))
        {
            PipelineModel pipeline = module.Pipeline!;

            writer.Line($"[\"{module.Module}\"] = new()");
            writer.Open("{");
            writer.Line($"Name = \"{module.Module}\",");
            writer.Line($"GroupSizeX = {pipeline.ThreadGroupSize[0]},");
            writer.Line($"GroupSizeY = {pipeline.ThreadGroupSize[1]},");
            writer.Line($"GroupSizeZ = {pipeline.ThreadGroupSize[2]},");
            writer.Line($"CodeResource = \"Pathetic.Renderer.Shaders.{module.OutputStem}.spv\",");
            writer.Line("Parameters =");
            writer.Open("[");

            foreach (ParameterModel parameter in pipeline.Parameters)
                writer.Line($"new ShaderParameter(\"{parameter.Name}\", ShaderResourceKind.{parameter.Kind}, {parameter.Space}, {parameter.Binding}),");

            writer.Close("],");
            writer.Close("},");
        }

        writer.Close("};");
        writer.Line();
        writer.Line("public static ShaderModule Get(string name) => All.TryGetValue(name, out ShaderModule? module)");
        writer.Line("    ? module");
        writer.Line("    : throw new InvalidOperationException($\"No precompiled shader module named '{name}'.\");");
        writer.Close("}");
        writer.Close("}");

        return writer.ToString();
    }
}
