using System.Globalization;
using Microsoft.CodeAnalysis.CSharp;
using Pathetic.Renderer.Shaders.Generator.Diagnostics;
using Pathetic.Renderer.Shaders.Generator.Models;

namespace Pathetic.Renderer.Shaders.Generator.Generation;

internal static class CSharpSourceEmitter
{
    private const string TargetNamespace = "Pathetic.Renderer.Shaders.Gpu";

    public static GeneratedSources Emit(IReadOnlyList<ModuleModel> modules)
    {
        Dictionary<string, string> sourceByModule = new(StringComparer.Ordinal);

        foreach (ModuleModel module in modules.OrderBy(static module => module.ModuleName, StringComparer.Ordinal))
            sourceByModule[module.ModuleName] = EmitModule(module);

        return new GeneratedSources(sourceByModule, EmitRegistry(modules));
    }

    public static string EmitModule(ModuleModel module)
    {
        CodeWriter writer = new();

        WriteHeader(writer, module);
        WriteBindings(writer, module);
        WriteGpuTypes(writer, module);

        return writer.ToString();
    }

    private static void WriteHeader(CodeWriter writer, ModuleModel module)
    {
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();

        if (module.Types.Count > 0)
        {
            writer.Line("using System.Runtime.InteropServices;");
            writer.Line();
        }
    }

    private static void WriteBindings(CodeWriter writer, ModuleModel module)
    {
        IReadOnlyList<ResourceBinding> bindings = module.Pipeline is { } pipeline
            ? [.. module.Bindings.Where(binding => pipeline.Parameters.Any(parameter => parameter.Name == binding.Name))]
            : module.Bindings;

        if (module.Pipeline is null && bindings.Count == 0)
            return;

        string className = Escape(module.ModuleName);

        writer.Line($"namespace {TargetNamespace}.Bindings");
        writer.Open("{");
        writer.Line($"public static class {className}");
        writer.Open("{");
        writer.Line($"public const string ModuleName = \"{module.ModuleName}\";");

        if (bindings.Count > 0)
            writer.Line();

        HashSet<string> memberNames = new(StringComparer.Ordinal) { "ModuleName" };

        foreach (ResourceBinding binding in bindings)
        {
            string memberName = ToPascalCase(binding.Name);

            // A member cannot share its enclosing type's name (CS0542).
            if (memberName == module.ModuleName)
                memberName += "Resource";

            if (!memberNames.Add(memberName))
                throw new ShaderCompilerException($"Resource '{binding.Name}' in module '{module.ModuleName}' maps to C# member '{memberName}', which is already taken.");

            writer.Line($"public static readonly {binding.Kind}Name {memberName} = new(\"{binding.Name}\");");
        }

        writer.Close("}");
        writer.Close("}");
        writer.Line();
    }

    private static void WriteGpuTypes(CodeWriter writer, ModuleModel module)
    {
        if (module.Types.Count == 0)
            return;

        writer.Line($"namespace {TargetNamespace}");
        writer.Open("{");

        foreach (TypeModel type in module.Types)
        {
            writer.Line();
            writer.Line($"[StructLayout(LayoutKind.Explicit, Size = {type.Size})]");
            writer.Line($"public record struct {Escape(type.Name)}");
            writer.Open("{");
            writer.Line($"public const int SizeInBytes = {type.Size};");

            foreach (FieldModel field in type.Fields)
                writer.Line($"[FieldOffset({field.Offset})] public {field.CsType} {Escape(field.Name)};");

            writer.Close("}");
        }

        writer.Close("}");
    }

    private static string EmitRegistry(IEnumerable<ModuleModel> modules)
    {
        CodeWriter writer = new();

        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line("namespace Pathetic.Renderer.Shaders");
        writer.Open("{");
        WriteResourceKinds(writer);
        writer.Line();
        WriteModuleTable(writer, modules);
        writer.Close("}");

        return writer.ToString();
    }

    private static void WriteResourceKinds(CodeWriter writer)
    {
        writer.Line("public enum ShaderResourceKind");
        writer.Open("{");

        foreach (BindingKind kind in Enum.GetValues<BindingKind>())
            writer.Line($"{kind},");

        writer.Close("}");
    }

    private static void WriteModuleTable(CodeWriter writer, IEnumerable<ModuleModel> modules)
    {
        writer.Line("public static class ShaderModules");
        writer.Open("{");
        writer.Line("public static readonly IReadOnlyDictionary<string, ShaderModule> All = new Dictionary<string, ShaderModule>(StringComparer.Ordinal)");
        writer.Open("{");

        foreach (ModuleModel module in modules.Where(static module => module.Pipeline is not null).OrderBy(static module => module.ModuleName, StringComparer.Ordinal))
        {
            PipelineModel pipeline = module.Pipeline!;

            writer.Line($"[\"{module.ModuleName}\"] = new()");
            writer.Open("{");
            writer.Line($"Name = \"{module.ModuleName}\",");
            writer.Line($"GroupSizeX = {pipeline.ThreadGroupSize.X},");
            writer.Line($"GroupSizeY = {pipeline.ThreadGroupSize.Y},");
            writer.Line($"GroupSizeZ = {pipeline.ThreadGroupSize.Z},");
            writer.Line($"SpirvResourceName = \"Pathetic.Renderer.Shaders.{module.ModuleName}.spv\",");
            writer.Line("Parameters =");
            writer.Open("[");

            foreach (PipelineParameter parameter in pipeline.Parameters)
                writer.Line($"new ShaderParameter(\"{parameter.Name}\", ShaderResourceKind.{parameter.Kind}, {parameter.Slot}, {parameter.Space}),");

            writer.Close("],");
            writer.Close("},");
        }

        writer.Close("};");
        writer.Line();
        writer.Line("public static ShaderModule Get(string name) => All.TryGetValue(name, out ShaderModule? module)");
        writer.Line("    ? module");
        writer.Line("    : throw new InvalidOperationException($\"No precompiled shader module named '{name}'.\");");
        writer.Close("}");
    }

    private static string ToPascalCase(string name)
    {
        string trimmed = name.TrimStart('_');

        if (trimmed.Length == 0)
            return Escape(name);

        return string.Concat(trimmed[..1].ToUpper(CultureInfo.InvariantCulture), trimmed.AsSpan(1));
    }

    private static string Escape(string name)
    {
        bool isLanguageKeyword = SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None;
        bool isContextualKeyword = SyntaxFacts.GetContextualKeywordKind(name) != SyntaxKind.None;
        return isLanguageKeyword || isContextualKeyword ? "@" + name : name;
    }
}
