using Microsoft.CodeAnalysis.CSharp;

namespace Pathetic.Slang.Generator;

internal static class Identifier
{
    public static string Escape(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(name) != SyntaxKind.None
            ? "@" + name
            : name;

    public static bool IsValid(string name)
    {
        if (name.Length == 0)
            return false;

        if (!char.IsLetter(name[0]) && name[0] != '_')
            return false;

        foreach (char character in name)
        {
            if (!char.IsLetterOrDigit(character) && character != '_')
                return false;
        }

        return true;
    }
}

internal static class ResourceRefsEmitter
{
    public static string Emit(string targetNamespace)
    {
        CodeWriter writer = new();

        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line($"namespace {targetNamespace};");
        writer.Line();

        EmitRef(writer, "TextureRef", null);
        EmitRef(writer, "MutableTextureRef", "TextureRef");
        EmitRef(writer, "SamplerRef", null);
        EmitRef(writer, "UniformBufferRef", null);
        EmitRef(writer, "BufferRef", null);
        EmitRef(writer, "MutableBufferRef", "BufferRef");

        return writer.ToString();
    }

    private static void EmitRef(CodeWriter writer, string name, string? convertsTo)
    {
        writer.Line($"public readonly record struct {name}(string Value)");
        writer.Open("{");
        writer.Line($"public static implicit operator string({name} value) => value.Value;");

        if (convertsTo is not null)
            writer.Line($"public static implicit operator {convertsTo}({name} value) => new(value.Value);");

        writer.Close("}");
        writer.Line();
    }

    public static bool TryResolveToken(string kind, out string token)
    {
        token = kind switch
        {
            "Texture" => "TextureRef",
            "MutableTexture" => "MutableTextureRef",
            "Sampler" => "SamplerRef",
            "UniformBuffer" => "UniformBufferRef",
            "BufferRead" => "BufferRef",
            "BufferReadWrite" => "MutableBufferRef",
            _ => "",
        };

        return token.Length > 0;
    }
}

internal static class ResourcesEmitter
{
    public static string Emit(string targetNamespace, SlangModuleModel module)
    {
        CodeWriter writer = new();

        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line($"namespace {targetNamespace};");
        writer.Line();
        writer.Line($"public static class {Identifier.Escape(module.Module)}");
        writer.Open("{");
        writer.Line("public static class Resources");
        writer.Open("{");
        writer.Line($"public const string ModuleName = \"{module.Module}\";");

        if (module.Bindings.Length > 0)
            writer.Line();

        foreach (BindingModel binding in module.Bindings)
        {
            ResourceRefsEmitter.TryResolveToken(binding.Kind, out string token);
            writer.Line($"public static readonly {token} {Identifier.Escape(binding.Name)} = new(\"{binding.Name}\");");
        }

        writer.Close("}");
        writer.Close("}");

        return writer.ToString();
    }
}

internal static class StructEmitter
{
    public static string Emit(string targetNamespace, SlangModuleModel module, TypeModel type)
    {
        CodeWriter writer = new();

        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line("using System.Runtime.InteropServices;");
        writer.Line();
        writer.Line($"namespace {targetNamespace};");
        writer.Line();
        writer.Line($"public static class {Identifier.Escape(module.Module)}");
        writer.Open("{");

        if (type.HasGpuLayout && type.Size is int size)
            writer.Line($"[StructLayout(LayoutKind.Explicit, Size = {size})]");
        else
            writer.Line("[StructLayout(LayoutKind.Sequential)]");

        writer.Line($"public record struct {Identifier.Escape(type.Name)}");
        writer.Open("{");

        if (type.HasGpuLayout && type.Size is int sizeInBytes)
            writer.Line($"public const int SizeInBytes = {sizeInBytes};");

        foreach (FieldModel field in type.Fields)
        {
            string attribute = type.HasGpuLayout ? $"[FieldOffset({field.Offset})] " : "";
            writer.Line($"{attribute}public {field.CsType} {Identifier.Escape(field.Name)};");
        }

        writer.Close("}");
        writer.Close("}");

        return writer.ToString();
    }
}
